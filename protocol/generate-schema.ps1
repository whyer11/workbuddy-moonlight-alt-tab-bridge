param(
    [string]$OutputRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
)

$ErrorActionPreference = 'Stop'
$schema = Get-Content -Raw -LiteralPath (Join-Path $PSScriptRoot 'bridge-schema.json') | ConvertFrom-Json
$utf8 = [System.Text.UTF8Encoding]::new($false)

function Escape-Java([string]$value) {
    return $value.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n')
}

function Escape-C([string]$value) {
    return $value.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n')
}

function Write-Generated([string]$relativePath, [string]$content) {
    $path = Join-Path $OutputRoot $relativePath
    $directory = Split-Path -Parent $path
    New-Item -ItemType Directory -Path $directory -Force | Out-Null
    [System.IO.File]::WriteAllText($path, ($content.TrimEnd() + "`n"), $utf8)
}

$javaRules = foreach ($rule in $schema.rules) {
    '            new RuleDefinition("{0}", "{1}", "{2}", "{3}", "{4}", {5}, {6})' -f `
        (Escape-Java $rule.id), (Escape-Java $rule.title), (Escape-Java $rule.padInput), `
        (Escape-Java $rule.padOutput), (Escape-Java $rule.windowsAction), `
        $rule.pad.ToString().ToLowerInvariant(), $rule.windows.ToString().ToLowerInvariant()
}
$javaRuleList = $javaRules -join ",`n"
$java = @"
package local.workbuddy.alttab.generated;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/** Generated by protocol/generate-schema.ps1. Do not edit. */
public final class GeneratedBridgeSchema {
    public static final int PROTOCOL_VERSION = $($schema.protocolVersion);
    public static final String PRODUCT_VERSION = "$($schema.productVersion)";
    public static final int STATUS_PORT = $($schema.statusPort);
    public static final int NONCE_HEX_LENGTH = $($schema.nonceHexLength);
    public static final int MAX_DATAGRAM_BYTES = $($schema.maxDatagramBytes);

    public static final List<RuleDefinition> RULES = Collections.unmodifiableList(Arrays.asList(
$javaRuleList
    ));

    private GeneratedBridgeSchema() {}

    public static final class RuleDefinition {
        public final String id;
        public final String title;
        public final String padInput;
        public final String padOutput;
        public final String windowsAction;
        public final boolean pad;
        public final boolean windows;

        private RuleDefinition(String id, String title, String padInput, String padOutput,
                               String windowsAction, boolean pad, boolean windows) {
            this.id = id;
            this.title = title;
            this.padInput = padInput;
            this.padOutput = padOutput;
            this.windowsAction = windowsAction;
            this.pad = pad;
            this.windows = windows;
        }
    }
}
"@

$padRules = @($schema.rules | Where-Object { $_.pad } | ForEach-Object { $_.id }) -join ','
$windowsRules = @($schema.rules | Where-Object { $_.windows } | ForEach-Object { $_.id }) -join ','
$header = @"
#ifndef WB_GENERATED_BRIDGE_SCHEMA_H
#define WB_GENERATED_BRIDGE_SCHEMA_H

/* Generated by protocol/generate-schema.ps1. Do not edit. */
#define WB_SCHEMA_PROTOCOL_VERSION $($schema.protocolVersion)
#define WB_SCHEMA_PRODUCT_VERSION "$(Escape-C $schema.productVersion)"
#define WB_SCHEMA_STATUS_PORT $($schema.statusPort)
#define WB_SCHEMA_NONCE_HEX_LENGTH $($schema.nonceHexLength)
#define WB_SCHEMA_MAX_DATAGRAM_BYTES $($schema.maxDatagramBytes)
#define WB_SCHEMA_PAD_RULES "$(Escape-C $padRules)"
#define WB_SCHEMA_WINDOWS_RULES "$(Escape-C $windowsRules)"

#endif
"@

Write-Generated 'android-bridge\app\src\main\java\local\workbuddy\alttab\generated\GeneratedBridgeSchema.java' $java
Write-Generated 'native-bridge\src\generated_bridge_schema.h' $header
Write-Generated 'windows-host\src\GeneratedBridgeSchema.h' $header
